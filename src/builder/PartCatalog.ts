export interface CraftPart {
  id: string;
  name: string;
  category: PartCategory;
  /** Which competition this part belongs to ('shared' for toppers used across all 3 events; defaults to 'flugtag') */
  competition?: CompetitionId | 'shared';
  emoji: string;
  primaryColor: string;
  accentColor: string;
  materialLabel: string;
  /** Weight in pounds (Pilot is 145 lbs, max competition rule is 400 lbs) */
  massLbs: number;
  /** Longitudinal position offset along craft axis (+forward/nose, -backward/tail) in meters */
  cgOffsetX: number;
  /** Aerodynamic lifting surface area in m^2 (or speed/pedal efficiency factor in Soapbox/Coaster) */
  wingAreaM2: number;
  /** Aerodynamic center offset along craft axis (+forward, -backward) */
  acOffsetX: number;
  /** Wing aspect ratio (span^2 / area) - higher means less induced drag */
  aspectRatio: number;
  /** Lift / Speed / Pedal coefficient multiplier */
  liftMultiplier: number;
  /** Parasitic drag / rolling resistance coefficient contribution */
  dragCoeff: number;
  /** Pitch damping / steering grip / lateral rail stability contribution */
  pitchStability: number;
  /** Judge creativity score bonus */
  creativityPoints: number;
  /** Structural durability (0.3 = snaps easily like cardboard, 1.0 = tough carbon/foam) */
  toughness: number;
  /** Extra ramp push / wheel rolling efficiency */
  pushEfficiency?: number;
  /** Stars required to unlock (0 = unlocked immediately from start!) */
  unlockStars: number;
  /** Kid-friendly visual badge */
  kidBadge: string;
}

