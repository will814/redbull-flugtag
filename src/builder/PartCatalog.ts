export type PartCategory = 'chassis' | 'wings' | 'tail' | 'nose' | 'topper' | 'trolley';

export interface CraftPart {
  id: string;
  name: string;
  category: PartCategory;
  emoji: string;
  primaryColor: string;
  accentColor: string;
  materialLabel: string;
  /** Weight in pounds (Pilot is 145 lbs, max competition rule is 400 lbs) */
  massLbs: number;
  /** Longitudinal position offset along craft axis (+forward/nose, -backward/tail) in meters */
  cgOffsetX: number;
  /** Aerodynamic lifting surface area in m^2 */
  wingAreaM2: number;
  /** Aerodynamic center offset along craft axis (+forward, -backward) */
  acOffsetX: number;
  /** Wing aspect ratio (span^2 / area) - higher means less induced drag */
  aspectRatio: number;
  /** Lift coefficient multiplier */
  liftMultiplier: number;
  /** Parasitic drag coefficient contribution */
  dragCoeff: number;
  /** Pitch damping / longitudinal stability contribution from tail surfaces */
  pitchStability: number;
  /** Judge creativity score bonus */
  creativityPoints: number;
  /** Structural durability (0.3 = snaps easily like cardboard, 1.0 = tough carbon/foam) */
  toughness: number;
  /** Extra ramp push rolling efficiency (for trolleys) */
  pushEfficiency?: number;
  /** Stars required to unlock (0 = unlocked immediately from start!) */
  unlockStars: number;
  /** Kid-friendly visual badge */
  kidBadge: string;
}

export interface CraftLoadout {
  name: string;
  chassis: string;
  wings: string;
  tail: string;
  nose: string;
  topper: string;
  trolley: string;
  paintTheme: PaintThemeId;
}

