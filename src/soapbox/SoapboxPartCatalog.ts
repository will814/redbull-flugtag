export interface SoapboxPart {
  id: string;
  name: string;
  category: SoapboxPartCategory;
  emoji: string;
  tagline: string;
  unlockStars: number;
  massLbs: number;
  /** Longitudinal CG contribution in meters (+X forward, -X rear) */
  cgX: number;
  /** Base CG height (for chassis) or CG height delta in meters */
  cgHeightOffsetMeters: number;
  /** Base axle track width in meters (for steering) or delta (for wheels/chassis) */
  trackWidthMeters: number;
  /** Aerodynamic drag factor (lower = faster downhill top speed) */
  aeroDragCdA: number;
  /** Cornering downforce bonus at high speed */
  downforceFactor: number;
  /** Rolling resistance coefficient (lower = faster roll) */
  rollingResistanceFactor: number;
  /** Lateral tire grip rating (0.4 to 1.35) */
  asphaltGrip: number;
  /** 0..1 mitigation of cobblestone chatter and soapy water slicks */
  roughTerrainRating: number;
  /** Wheel radius in meters (for wheels category) */
  wheelRadiusMeters: number;
  /** Suspension vertical travel in meters (prevents bottoming out on kicker jumps) */
  suspensionTravelMeters: number;
  /** Anti-rollover bar stiffness (0..1, reduces chassis roll angle in turns) */
  antiRollStiffness: number;
  /** Mechanical braking power (0.3 to 1.25) */
  brakePower: number;
  /** 0..1 resistance to brake heat buildup and fade (1.0 = zero brake fade) */
  brakeHeatResistance: number;
  /** 0..1 reduction in hay-bale impact speed loss & structural damage */
  hayPlowProtection: number;
  /** 0..1 ease of initiating & holding controllable power-slide drifts */
  driftAgility: number;
  /** Structural toughness against crashes and hard jump landings */
  structuralToughness: number;
  /** Judge creativity & crowd flair points */
  creativityBonus: number;
}

